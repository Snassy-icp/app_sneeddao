// Regenerates src/tokensafety/dfinityReleases.js: the SHA-256 of every Wasm in DFINITY's
// standalone ICRC ledger suite releases (github.com/dfinity/ic, tags ledger-suite-icrc-*). A
// canister's module hash equals the SHA-256 of the .wasm.gz it was installed from, so Token
// Studio can recognise ledgers installed from an official release that SNS-W never listed.
//   node scripts/ledger-release-hashes.mjs
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const API = 'https://api.github.com/repos/dfinity/ic/releases?per_page=100&page=';
const rows = [];
for (let page = 1; page <= 20; page++) {
    const releases = await (await fetch(API + page, { headers: { Accept: 'application/vnd.github+json' } })).json();
    if (!Array.isArray(releases) || releases.length === 0) break;
    for (const r of releases.filter((x) => x.tag_name.startsWith('ledger-suite-icrc-'))) {
        const date = r.tag_name.replace('ledger-suite-icrc-', '');
        const wasms = r.assets.filter((a) => /^ic-icrc1-(ledger|index-ng|archive)(-u256)?\.wasm\.gz$/.test(a.name));
        const sums = r.assets.find((a) => a.name === 'SHA256SUMS');
        const known = new Map();
        if (sums) for (const line of (await (await fetch(sums.browser_download_url)).text()).split('\n')) {
            const [h, n] = line.trim().split(/\s+/);
            if (h && n) known.set(n.replace(/^\*/, ''), h);
        }
        for (const a of wasms) {
            const hash = known.get(a.name) || createHash('sha256').update(Buffer.from(await (await fetch(a.browser_download_url)).arrayBuffer())).digest('hex');
            const kind = a.name.includes('ledger') ? 'ledger' : a.name.includes('index') ? 'index' : 'archive';
            rows.push([hash, date, kind, a.name.includes('u256')]);
        }
    }
}
rows.sort((a, b) => (a[1] < b[1] ? 1 : a[1] > b[1] ? -1 : a[2].localeCompare(b[2])));
const body = rows.map(([h, d, k, u]) => `    '${h}': { release: '${d}', kind: '${k}'${u ? ', u256: true' : ''} },`).join('\n');
writeFileSync(new URL('../src/tokensafety/dfinityReleases.js', import.meta.url), `// Generated by scripts/ledger-release-hashes.mjs (${new Date().toISOString().slice(0, 10)}): module hashes of DFINITY's
// standalone ICRC ledger suite releases (github.com/dfinity/ic, ledger-suite-icrc-*). Do not edit.
export const DFINITY_LEDGER_RELEASES = {
${body}
};
`);
console.log(`${rows.length} hashes from ${new Set(rows.map((r) => r[1])).size} releases`);
